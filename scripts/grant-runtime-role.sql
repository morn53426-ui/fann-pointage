-- Droits runtime minimaux des opérations servies par l'API. Pas de SUPERUSER, DDL ni BYPASSRLS.
-- L'identité métier est contrôlée par l'API ; fann_app reste un rôle technique sans connexion utilisateur directe.
GRANT USAGE ON SCHEMA public TO fann_app;
GRANT SELECT, INSERT, UPDATE ON TABLE agents, services, agent_affectations TO fann_app;
